import { expect, test } from '@playwright/test'

test('실제 자료가 비어 있으면 첫 화면을 가상 샘플로 명확하게 표시한다', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.weapon-card')).toHaveCount(3)
  await expect(page.locator('.weapon-card').first().locator('strong')).toBeInViewport()
  await expect(page.locator('.sample-banner')).toContainText('가상 샘플')
  await expect(page.getByTestId('current-control')).toHaveText('62')
  await expect(page.locator('.schematic').getByRole('img')).toBeVisible()
  await page.getByRole('button', { name: '전면전 (0)', exact: true }).click()
  await expect(page.locator('.weapon-card')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '개조 작업대', exact: true })).toContainText('전면전 총기 자료 미등록')
  await expect(page.getByTestId('current-control')).toHaveCount(0)
  await expect(page.locator('[data-slot]')).toHaveCount(0)
  await page.getByRole('button', { name: '샘플 (3)', exact: true }).click()
  await expect(page.getByTestId('current-control')).toHaveText('62')
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
})

test('로고가 샘플 개조와 필터 및 URL 조각을 초기화한다', async ({ page }) => {
  await page.goto('/?v=home-test#workbench')
  await page.getByRole('button', { name: /SM-02 스위프트/ }).click()
  await page.locator('[data-slot="muzzle"]').click()
  await page.getByRole('button', { name: /제어형 제퇴기/ }).click()
  await page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' }).fill('스위프트')
  await page.getByRole('button', { name: '기관단총', exact: true }).click()
  await page.getByRole('link', { name: '델타 랩 홈', exact: true }).click()
  await expect(page.locator('.weapon-card')).toHaveCount(3)
  await expect(page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' })).toHaveValue('')
  await expect(page.getByRole('button', { name: '전체 (3)', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('current-control')).toHaveText('62')
  await expect(page.locator('.has-part')).toHaveCount(0)
  await expect(page.locator('#home-title')).toBeFocused()
  await expect(page).toHaveURL(/\?v=home-test$/)
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)
})

test('빈 자료 탭에서 키보드로 홈 복귀하고 데이터 안내를 구분한다', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '전면전 기본 총기 자료', exact: true }).click()
  await page.getByRole('button', { name: '데이터 안내', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('전면전 자료 안내')
  await expect(page.getByRole('dialog')).toContainText('나무위키')
  await expect(page.getByRole('dialog')).toContainText('등록을 보류')
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: '델타 랩 홈', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('current-control')).toHaveText('62')
  await expect(page.locator('#home-title')).toBeFocused()
})
