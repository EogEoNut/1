import { expect, test } from '@playwright/test'

test('첫 작업대에 수록 총기 전체를 표시하고 실제 총기 정보를 직접 선택한다', async ({ page }) => {
  await page.goto('/')
  const workbench = page.getByRole('region', { name: '개조 작업대', exact: true })
  await expect(page.locator('.weapon-card')).toHaveCount(69)
  await expect(page.locator('.weapon-card').first().locator('strong')).toBeInViewport()
  await expect(workbench.getByRole('heading', { name: 'M4A1', exact: true })).toBeVisible()
  await expect(workbench.locator('.warfare-specs > div').filter({ hasText: '발사 속도' })).toContainText('800')
  await expect(workbench.getByRole('radio')).toHaveCount(9)
  await workbench.getByRole('radio', { name: /416实用后握把/ }).check()
  await expect(page.getByTestId('warfare-stat-handling').locator('strong')).toHaveText('60')
  await page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' }).fill('AKM')
  await page.locator('.weapon-card').click()
  await expect(workbench.getByRole('heading', { name: 'AKM', exact: true })).toBeVisible()
  await expect(workbench.getByRole('radio')).toHaveCount(16)
  await expect(page.getByTestId('warfare-stat-control').locator('strong')).toHaveText('39')
  await page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' }).fill('AWM')
  await page.locator('.weapon-card').click()
  await expect(workbench.getByRole('heading', { name: 'AWM', exact: true })).toBeVisible()
  await expect(workbench).toContainText('해당 총기의 기본 수치는 아직 수록하지 않았습니다.')
  await expect(page.getByTestId('warfare-stat-control').locator('strong')).toHaveText('미확인')
  await expect(workbench.getByRole('radio')).toHaveCount(0)
  await expect(page.locator('.sample-tag')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
})

test('통합 목록 필터가 샘플과 관측 자료를 구분하고 작업대를 연결한다', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '전면전 (66)', exact: true }).click()
  await expect(page.locator('.weapon-card')).toHaveCount(66)
  await page.getByRole('button', { name: '샘플 (3)', exact: true }).click()
  await expect(page.locator('.weapon-card')).toHaveCount(3)
  await expect(page.getByTestId('current-control')).toHaveText('62')
  await page.locator('[data-slot="muzzle"]').click()
  await page.getByRole('button', { name: /제어형 제퇴기/ }).click()
  await expect(page.getByTestId('current-control')).toHaveText('72')
  await page.getByRole('button', { name: '전체 (69)', exact: true }).click()
  await page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' }).fill('M4A1')
  await page.locator('.weapon-card').click()
  await expect(page.getByTestId('current-control')).toHaveCount(0)
  await expect(page.getByTestId('warfare-stat-control').locator('strong')).toHaveText('41')
  await page.getByRole('button', { name: '데이터 안내', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('전면전 자료 안내')
  await expect(page.getByRole('dialog')).toContainText('게임 내 미검증')
})

test('로고가 샘플 구성과 필터를 초기화하고 첫 화면으로 돌아간다', async ({ page }) => {
  await page.goto('/?v=home-test#workbench')
  await page.getByRole('button', { name: '가상 샘플 작업대', exact: true }).click()
  await page.getByRole('button', { name: /SM-02 스위프트/ }).click()
  await page.locator('[data-slot="muzzle"]').click()
  await page.getByRole('button', { name: /제어형 제퇴기/ }).click()
  await page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' }).fill('스위프트')
  await page.getByRole('button', { name: '기관단총', exact: true }).click()
  await page.getByRole('link', { name: '델타 랩 홈', exact: true }).click()
  await expect(page.locator('.weapon-card')).toHaveCount(69)
  await expect(page.getByRole('textbox', { name: '총기 이름 또는 종류 검색' })).toHaveValue('')
  await expect(page.getByRole('button', { name: '전체 (69)', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('region', { name: '개조 작업대', exact: true }).getByRole('heading', { name: 'M4A1', exact: true })).toBeVisible()
  await expect(page.getByTestId('warfare-stat-handling').locator('strong')).toHaveText('58')
  await expect(page.getByRole('radio', { checked: true })).toHaveCount(0)
  await expect(page.locator('#home-title')).toBeFocused()
  await expect(page).toHaveURL(/\?v=home-test$/)
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)
  await page.getByRole('button', { name: '가상 샘플 작업대', exact: true }).click()
  await expect(page.getByTestId('current-control')).toHaveText('62')
  await expect(page.locator('.has-part')).toHaveCount(0)
})

test('자료 탭에서도 키보드로 홈에 복귀하며 관측 부품 선택을 초기화한다', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('radio', { name: /416实用后握把/ }).check()
  await page.getByRole('button', { name: '전면전 실제 자료 (부분 수집)', exact: true }).click()
  await page.getByRole('textbox', { name: '총기 검색 (66종)' }).fill('AKM')
  await page.locator('.warfare-weapon-list button').click()
  await page.getByRole('radio', { name: /X25U Angled Combat Grip/ }).check()
  await page.getByRole('link', { name: '델타 랩 홈', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.warfare-weapon-list')).toHaveCount(0)
  await expect(page.locator('.weapon-card')).toHaveCount(69)
  await expect(page.getByTestId('warfare-stat-handling').locator('strong')).toHaveText('58')
  await expect(page.getByRole('radio', { checked: true })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: '선호 전투 스타일' })).toHaveValue('balanced')
  await expect(page.locator('#home-title')).toBeFocused()
})
